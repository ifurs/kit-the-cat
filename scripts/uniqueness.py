"""Uniqueness check for a crowded chat + combinatorial count → docs/sprites/COMBINATIONS.md

    uv run python scripts/uniqueness.py
"""
import itertools
import math
import random
import statistics
import time
from pathlib import Path

from kit_the_cat import sprites as S

OUT = Path(__file__).resolve().parent.parent / "docs" / "sprites" / "COMBINATIONS.md"
CHAT = 200


def chat(seed: int, breed_share: float = 0.0) -> list[S.Genome]:
    """CHAT pets joining one by one; some are children of two pets already in the chat."""
    rng, pets = random.Random(seed), []
    for _ in range(CHAT):
        parents = tuple(rng.sample(pets, 2)) if len(pets) > 2 and rng.random() < breed_share else None
        pets.append(S.unique_genome(rng.choice(S.SPECIES), pets, rng, parents=parents))
    return pets


def stats(pets: list[S.Genome]) -> dict:
    ds = [S.distance(a, b) for a, b in itertools.combinations(pets, 2)]
    nn = [min(S.distance(p, o) for o in pets if o is not p) for p in pets]
    keys = [S.visible_key(p) for p in pets]
    return dict(min=min(ds), avg=statistics.mean(ds), nn_min=min(nn), nn_avg=statistics.mean(nn),
                below4=sum(d < 4 for d in nn), dup=len(keys) - len(set(keys)))


def timing() -> tuple[float, float, float]:
    rng = random.Random(3)
    lk = S.Look(genes=S.random_genome("fox", rng), stage=3, mood="happy", role="angel", background="village~autumn~rain",
                items=["wizard", "sunglasses", "chain", "vyshyvanka", "cape", "sabre", "sparkles", "rain"])
    lk2 = S.Look(genes=S.random_genome("cat", rng), stage=3, role="vampire+cyborg", background="kyiv~night~snow",
                 items=[S.random_item(s, rng) + "@3" for s in S.GEN_SLOTS])
    S.render_gif(lk)
    out = []
    for look in (lk, lk2):
        t = time.perf_counter()
        for _ in range(10):
            S.render_gif(look)
        out.append((time.perf_counter() - t) / 10 * 1000)
    t = time.perf_counter()
    S.render_group([S.Look(genes=S.random_genome(rng.choice(S.SPECIES), rng), stage=3) for _ in range(12)], "meadow")
    out.append((time.perf_counter() - t) * 1000)
    return tuple(out)


def combos() -> tuple[list[tuple[str, int, str]], int, int, int]:
    rows = []
    genes = math.prod(len(S.GENES[g]) for g in S.VISIBLE)
    rows.append(("species", len(S.SPECIES), "pig cat dog fox horse axolotl"))
    for g in S.VISIBLE:
        rows.append((f"gene `{g}`", len(S.GENES[g]), ", ".join(S.GENES[g])))
    colour = 36 * 5 * 5  # base colour buckets: 10° hue × 5 sat × 5 value
    colour2 = 6 + 36 * 3  # pattern colour: 6 natural + mutant hue buckets × 3 shades
    iris = len(S.IRIS) ** 2  # left/right (right differs only for hetero eyes, upper bound)
    rows.append(("base colour buckets (hue 36 × sat 5 × val 5)", colour, "continuous HSV, bucketed for counting"))
    rows.append(("pattern colour buckets", colour2, "6 natural + 36 hues × 3 shades"))
    rows.append(("iris colours (l × r)", iris, "right eye only differs for `hetero`"))
    look = len(S.SPECIES) * genes * colour * colour2 * iris
    tints = len(S.TINTS)
    item_total = 1
    for slot in S.SLOTS:
        fixed = sum(1 for v in S.ITEMS.values() if v[1] == slot)
        gen = S.gen_count(slot) if slot in S.GEN else 0
        n = 1 + (fixed + gen) * tints
        item_total *= n
        rows.append((f"slot `{slot}`", n, f"empty + ({fixed} fixed + {gen:,} generated) × {tints} tints"))
    bases = len(S.BACKGROUNDS)
    groups = [sum(1 for _, o, _ in S.BG_MODS.values() if o == k) + 1 for k in (0, 1, 2)]
    bg = bases * math.prod(groups)
    rows.append(("backgrounds", bg, f"{bases} bases × (1+{groups[0] - 1}) seasons × (1+{groups[1] - 1}) times × "
                                    f"(1+{groups[2] - 1}) weathers"))
    roles = 1 + len(S.ROLES) + math.comb(len(S.ROLES), 2)
    rows.append(("roles", roles, "none + 8 single + 28 pairs (`vampire+cyborg`)"))
    rows.append(("stage × mood × (fat/dirty/hungry)", 4 * 7 * 2 * 2 * 2, "4 hatched stages × 7 moods × 3 on/off flags"))
    total = look * item_total * bg * roles * 4 * 7 * 8
    return rows, total, look, genes


def sci(n: int) -> str:
    e = len(str(n)) - 1
    return f"{n / 10 ** e:.2f}·10^{e}"


def main() -> None:
    lines = []
    results = []
    for seed, share in ((1, 0.0), (2, 0.0), (3, 0.3), (4, 0.6)):
        t = time.perf_counter()
        st = stats(chat(seed, share))
        st["sec"] = time.perf_counter() - t
        results.append((seed, share, st))
        print(f"seed {seed} breed {share:.0%}: {st}")
    rows, total, look, genes = combos()
    t_full, t_gen, t_zoo = timing()
    print(f"render_gif fully equipped: {t_full:.0f} ms, all-generated+2 roles: {t_gen:.0f} ms, zoo(12) png: {t_zoo:.0f} ms")
    print("total combinations:", sci(total))

    lines += ["# Sprite combinatorics", "",
              "Generated by `uv run python scripts/uniqueness.py` — do not edit by hand.", "",
              "## Building blocks", "", "| part | variants | notes |", "|---|---:|---|"]
    lines += [f"| {a} | {b:,} | {c} |" for a, b, c in rows]
    lines += ["", "## Totals", "",
              f"* discrete genomes (species × genes): **{len(S.SPECIES) * genes:,}**",
              f"* pet looks incl. colour buckets: **{sci(look)}** (plus per-pet pattern seed placement)",
              f"* generated items: **{S.gen_count():,}** distinct (`gen:<slot>:<base36>`), "
              f"fixed items: {len(S.ITEMS)}, × {len(S.TINTS)} tints (tints are an upper bound: grey parts stay grey)",
              f"* **everything combined** (look × items in all 8 slots × backgrounds × roles × stage/mood/state): "
              f"**{sci(total)}**", "",
              f"## Uniqueness in a {CHAT}-pet chat", "",
              "Each pet is created with `unique_genome(species, others, rng)` against all pets already in the chat;"
              " some runs mix in children bred from two chat members (`parents=`).", "",
              "| run | breed share | min pair dist | avg pair dist | min nearest | avg nearest | nearest < 4 | duplicate looks |",
              "|---|---:|---:|---:|---:|---:|---:|---:|"]
    lines += [f"| seed {s} | {sh:.0%} | {st['min']:.2f} | {st['avg']:.2f} | {st['nn_min']:.2f} | {st['nn_avg']:.2f} | "
              f"{st['below4']} | **{st['dup']}** |" for s, sh, st in results]
    lines += ["", "`distance` = number of differing visible genes (+species) + up to 2.0 for colour difference; "
              "duplicate look = same `visible_key` (species + all 10 visible genes). `unique_genome` guarantees 0 duplicates.",
              "", "## Render timing", "",
              f"* `render_gif` fully equipped (8 fixed items, role angel, `village~autumn~rain`): **{t_full:.0f} ms**",
              f"* `render_gif` 8 tinted generated items + `vampire+cyborg` + `kyiv~night~snow`: **{t_gen:.0f} ms**",
              f"* `render_group` zoo of 12 (PNG): **{t_zoo:.0f} ms**", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT)
    assert all(st["dup"] == 0 for *_, st in results), "duplicate looks!"


if __name__ == "__main__":
    main()
