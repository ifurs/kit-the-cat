"""Dream quests: every pet has a dream (persona.GOALS, req goal=…), and each dream has a three-step path to it.
Step 1 comes at random (often — it is the pet's dream); a good choice sets flag dr_<goal>=1 and schedules step 2,
step 2 sets 2 and schedules the finale, the finale fulfils the dream (flag dream_done, «Мрія збулася»). A failure
schedules another try later, and a few choices give the dream up on purpose. Risky choices can hurt badly — a pet
with low health can die chasing its dream. Placeholders: {name} {owner} {food} {dream}.
"""
from .dsl import ch, ev, o

UP = (2, 4)
GROWN = (3, 4)
DONE = "Мрія збулася"


def step(g: str, n: int) -> dict:
    """Effects of a choice that moves the dream forward to step n+1."""
    return dict(flag={f"dr_{g}": n}, then=(f"dr_{g}_{n + 1}", "1y"))


def retry(g: str, n: int, after: str = "2y") -> dict:
    """Effects of a failed attempt: the same step comes back later (engine.FOLLOWUP_MAX tries in a life)."""
    return dict(then=(f"dr_{g}_{n}", after))


def done(g: str) -> dict:
    """Effects of a fulfilled dream."""
    return dict(flag={f"dr_{g}": 3, "dream_done": 1}, achievement=DONE, mood=30, xp=40)


def first(g: str, text: str, *choices, stage=UP, bg: str = "") -> object:
    return ev(f"dr_{g}_1", text, *choices, req=dict(goal=g, stage=stage, noflag=f"dr_{g}"), w=4.0, bg=bg,
              time="1m")


def later(g: str, n: int, text: str, *choices, bg: str = "") -> object:
    return ev(f"dr_{g}_{n}", text, *choices, req=dict(flag={f"dr_{g}": n - 1}), followup=True, bg=bg,
              time="3m" if n == 2 else "6m")


