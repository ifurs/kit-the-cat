def _all_texts():
    for e in ALL:
        yield e.id, e.text
        for c in e.choices:
            yield f"{e.id}/{c.label}", c.label
            for out in c.outs + c.fail:
                yield f"{e.id}/{c.label}", out.text


def test_every_text_formats_cleanly_for_a_long_name_and_an_other_pet():
    p, other = _pet(), _pet()
    p.name, other.name = "Крилатий з Троєщини", "Мурка Велика"
    p.owner_name, other.owner_name = "Оля", "Тарас"
    for where, text in _all_texts():
        out = p.fmt(text, other)
        assert not re.search(r"\{[a-z_]+\}", out), (where, out)
    for text, _fx, _w in E.TAILS:
        assert "{" not in p.fmt(text, other), text


