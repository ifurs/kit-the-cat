@pytest.mark.parametrize("name,forms", NAME_FORMS.items())
def test_every_base_name(name, forms):
    d = decline(name)
    assert (d["gen"], d["dat"], d["ins"]) == forms
    assert d["nom"] == name


def test_the_table_covers_every_name_in_the_pools():
    pool = {n for names in NAMES.values() for n in names}
    assert not pool - set(NAME_FORMS), sorted(pool - set(NAME_FORMS))


@pytest.mark.parametrize("name,forms", FULL.items())
def test_full_paradigms(name, forms):
    assert tuple(decline(name)[c] for c in CASES) == forms


def test_the_tail_after_a_preposition_stays_as_it_is():
    assert decline("Бублик Грозний із Жмеринки")["gen"] == "Бублика Грозного із Жмеринки"
    assert decline("Мурчик з Борщагівки")["ins"] == "Мурчиком з Борщагівки"
    assert decline("Пушок Із Жмеринки")["dat"] == "Пушкові Із Жмеринки"
    assert decline("Рижик № 12")["gen"] == "Рижика № 12"
    assert decline("Лис від Хитрих Лисів")["acc"] == "Лиса від Хитрих Лисів"
    assert inflect("Хитромудрий з Троєщини", "loc") == "Хитромудрому з Троєщини"
    assert decline("з Троєщини") == {c: "з Троєщини" for c in CASES}


def test_suffix_adjectives_decline_with_the_name():
    assert inflect("Мурчик Неймовірний", "gen") == "Мурчика Неймовірного"
    assert inflect("Барсик Молодший", "ins") == "Барсиком Молодшим"
    assert inflect("Тузик Вічно Голодний", "dat") == "Тузикові Вічно Голодному"
    assert inflect("Рекс Третій", "gen") == "Рекса Третього"
    assert inflect("Жучка Сором'язлива", "gen") == "Жучки Сором'язливої"
    assert inflect("Пухнастий", "gen") == "Пухнастого"


def test_indeclinable_and_foreign_words_stay_nominative():
    for name in UNCHANGED:
        assert all(f == name for f in decline(name).values()), name
    assert decline("Barsyk Бублик")["gen"] == "Barsyk Бублика"
    assert decline("Бублик 2")["gen"] == "Бублика 2"
    assert decline("Бублик 😺")["ins"] == "Бубликом 😺"
    assert decline("«Барсик»")["gen"] == "«Барсика»"
    assert decline("Бублик,")["gen"] == "Бублика,"


def test_uppercase_and_lowercase_names_keep_their_case():
    assert inflect("БАРСИК", "gen") == "БАРСИКА"
    assert inflect("барсик", "gen") == "барсика"
    assert inflect("Гуппі-бос", "ins") == "Гуппі-босом"


def test_a_feminine_name_on_a_consonant_is_indeclinable_but_names_on_a_decline():
    assert decline("Любов", "f")["gen"] == "Любов"
    assert decline("Мурка", "f")["gen"] == "Мурки"
    assert decline("Любов", "m")["gen"] == "Любова"
    assert inflect("Мурка Велика", "gen", "f") == "Мурки Великої"


